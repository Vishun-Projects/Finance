type TagColor = 'red' | 'green' | 'yellow' | 'blue' | 'purple' | 'orange';

const tagStyles: Record<string, string> = {
  red: 'bg-red-500/10 text-red-600 dark:text-red-400',
  green: 'bg-green-500/10 text-green-700 dark:text-green-400',
  yellow: 'bg-amber-500/10 text-amber-700 dark:text-amber-400',
  blue: 'bg-blue-500/10 text-blue-700 dark:text-blue-400',
  purple: 'bg-purple-500/10 text-purple-700 dark:text-purple-400',
  orange: 'bg-orange-500/10 text-orange-700 dark:text-orange-400',
  gray: 'bg-muted text-muted-foreground',
};

export function Pill({
  label,
  active,
  onClick,
  icon,
}: {
  label: string;
  active: boolean;
  onClick: () => void;
  icon?: ReactNode;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      className={cn(
        'flex items-center gap-1.5 whitespace-nowrap rounded-md border-none px-3 py-1.5 text-[13px] transition-colors',
        active
          ? 'bg-foreground font-medium text-background'
          : 'bg-transparent font-normal text-muted-foreground hover:bg-surface hover:text-foreground',
      )}
    >
      {icon}
      {label}
    </button>
  );
}

export function Card({
  children,
  className,
  style,
}: {
  children: ReactNode;
  className?: string;
  style?: React.CSSProperties;
}) {
  return (
    <div className={cn('card-base px-5 py-4 text-foreground', className)} style={style}>
      {children}
    </div>
  );
}

export function Tag({ children, color }: { children: ReactNode; color?: TagColor | string }) {
  const key = color ?? 'gray';
  return (
    <span className={cn('inline-block rounded px-2 py-0.5 text-[11px] font-medium', tagStyles[key] || tagStyles.gray)}>
      {children}
    </span>
  );
}

export function ProsCons({ pros, cons }: { pros: string[]; cons: string[] }) {
  return (
    <div className="mt-2.5 grid grid-cols-1 gap-2.5 sm:grid-cols-2">
      <div>
        {pros.map((p, i) => (
          <div key={i} className="mb-1.5 flex items-start gap-1.5 text-xs text-green-700 dark:text-green-400">
            <span className="mt-px shrink-0">{icons.check}</span>
            {p}
          </div>
        ))}
      </div>
      <div>
        {cons.map((c, i) => (
          <div key={i} className="mb-1.5 flex items-start gap-1.5 text-xs text-red-600 dark:text-red-400">
            <span className="mt-px shrink-0">{icons.x}</span>
            {c}
          </div>
        ))}
      </div>
    </div>
  );
}

